/// BS month lengths are not derivable - they vary between 29 and 32 days and
/// are published each year by Nepal's calendar committee - so a table is the
/// only way. These rows come from three independent calendars
/// (medic/bikram-sambat, ernilambar/nepali-date and sarbagyastha/nepali_utils),
/// which agree on every month from 2000 to 2083 BS, and all three place the
/// published dates: 1 Jan 2000 = Poush 17, 2056; Constitution Day, 20 Sep 2015
/// = Asoj 3, 2072; and the new-year days of 2080 to 2083.
///
/// The three sources part company from 2084 BS (April 2027) onward, which is
/// the committee's doing rather than theirs - those years are not fixed yet.
/// The rows below follow the two that agree. Worth re-checking against an
/// official calendar before April 2027.
///
/// Written out rather than taken from a package: this is one table and one
/// loop, and it is the kind of thing worth being able to verify in the repo.
