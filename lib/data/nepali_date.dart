  /// Null outside the table rather than a wrong date: a banner with no date on
  /// it is better than a banner with the wrong one.
  static NepaliDate? from(DateTime date) {
    final day = DateTime(date.year, date.month, date.day);
    var remaining = day.difference(_epoch).inDays;
    if (remaining < 0) return null;

    var year = _epochYear;
    while (true) {
      final lengths = _monthLengths[year];
      if (lengths == null) return null;
      final inYear = lengths.reduce((a, b) => a + b);
      if (remaining < inYear) break;
      remaining -= inYear;
      year++;
    }

    final lengths = _monthLengths[year]!;
    var month = 0;
    while (remaining >= lengths[month]) {
      remaining -= lengths[month];
      month++;
    }

    // DateTime.weekday is 1 = Monday .. 7 = Sunday; Nepali weeks start Sunday.
    return NepaliDate(year, month + 1, remaining + 1, day.weekday % 7 + 1);
  }

  static NepaliDate? today() => from(DateTime.now());

  String get monthName => monthNames[month - 1];
  String get monthNameNepali => monthNamesNepali[month - 1];
  String get weekdayName => weekdayNames[weekday - 1];
  String get weekdayNameNepali => weekdayNamesNepali[weekday - 1];

  /// "Asoj 27, 2083"
  String get formatted => '$monthName $day, $year';

  /// "असोज २७, २०८३"
  String get inNepali =>
      '$monthNameNepali ${_devanagari(day)}, ${_devanagari(year)}';

  @override
  String toString() => formatted;

  static const _digits = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];

  static String _devanagari(int value) => value
      .toString()
      .split('')
      .map((c) => _digits[int.parse(c)])
      .join();
